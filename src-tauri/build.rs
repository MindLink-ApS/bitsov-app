    // Call sealing is one switch for both halves: the renderer's VITE_CALL_SEAL
    // and the host's `call-seal` feature. Refuse a build with only one of them.
    let call_seal = std::env::var_os("CARGO_FEATURE_CALL_SEAL").is_some();
    let call_seal_env = std::env::var("VITE_CALL_SEAL").ok().as_deref() == Some("sealed");
    if call_seal != call_seal_env {
        panic!("call sealing needs both the `call-seal` feature and VITE_CALL_SEAL=sealed, or neither");
    }

