    // Listing the commands opts out of Tauri's default allow-all for app commands.
    // Each name gets `allow-<slug>` and `deny-<slug>` permissions. Only the main
    // window capability grants the allows. Do not grant the deny permissions:
    // Tauri 2.11 applies a command deny to every window.
    //
    // The default permissions glob would also read `permissions/autogenerated`
    // and define each permission twice. This pattern matches no extra files.
