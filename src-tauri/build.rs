    println!("cargo:rerun-if-env-changed=VITE_CALL_SEAL");
    println!("cargo:rerun-if-changed=capabilities");
    println!("cargo:rerun-if-changed=mobile-capabilities");

    println!("cargo:rerun-if-changed=capabilities-call-seal");
