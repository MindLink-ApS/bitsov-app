import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { render } from 'solid-js/web';
import { AiPairingPanel, type AiPairingView } from '../src/control/AiPairingPanel';
let dispose: (() => void) | undefined;
const mount = document.createElement('div');
beforeEach(() => document.body.appendChild(mount));
afterEach(() => { dispose?.(); mount.replaceChildren(); mount.remove(); vi.useRealTimers(); });
const view = (state: AiPairingView['state']): AiPairingView => ({ pair_window:'konsensus pair-window --seconds 300', state, client_id: state === 'none' ? null : 'a1', grant: null, pending: null, grant_revoke: 'konsensus grant-revoke --client-id a1', pair_revoke: 'konsensus pair-revoke --client-id a1' });
it('creates a separate AI pairing, requires payees, and shows the console approval', async () => {
  const requests: unknown[] = [];
  const request = async (r: unknown) => { requests.push(r); return (r as {action:string}).action === 'status' ? view('none') : (r as {action:string}).action === 'create' ? view('paired') : { ...view('pending'), pending: { owner_action: 'konsensus grant --op ab12 --budget 1000 --per-call 55', expires_at_ms: Date.now() + 60000 } }; };
  dispose = render(() => <AiPairingPanel request={request} />, mount);
  await vi.waitFor(() => expect(mount.querySelector('[data-ai-create]')).not.toBeNull());
  (mount.querySelector('[data-ai-create]') as HTMLButtonElement).click();
  await vi.waitFor(() => expect(mount.querySelector('[data-ai-grant-request]')).not.toBeNull());
  const grant = mount.querySelector('[data-ai-grant-request]') as HTMLButtonElement;
  expect(grant.disabled).toBe(true);
  const input = mount.querySelector('textarea')!;
  input.value = '02' + 'ab'.repeat(32); input.dispatchEvent(new Event('input', {bubbles:true}));
  grant.click();
  await vi.waitFor(() => expect(mount.textContent).toContain('konsensus grant --op ab12'));
  expect(requests).toContainEqual({action:'request_grant', payees:['02' + 'ab'.repeat(32)]});
  expect(mount.textContent).toContain('55 sats all-in');
});
it('polls console revocation and clears stale grant authority on read failure', async () => {
  vi.useFakeTimers();
  let current = { ...view('active'), grant: { budget_msat:1000000, remaining_msat:900000, per_call_max_msat:55000, expires_at_ms:Date.now()+60000, payees:['ab'.repeat(32)], paused:false } } as AiPairingView;
  let fail = false;
  dispose = render(() => <AiPairingPanel request={async () => { if(fail) throw new Error('offline'); return current; }} />, mount);
  await vi.advanceTimersByTimeAsync(1);
  expect(mount.querySelector('[data-ai-state="active"]')).not.toBeNull();
  current = view('revoked'); await vi.advanceTimersByTimeAsync(5000);
  expect(mount.querySelector('[data-ai-state="revoked"]')).not.toBeNull();
  expect(mount.querySelector('[data-ai-grant]')).toBeNull();
  fail = true; await vi.advanceTimersByTimeAsync(5000);
  expect(mount.textContent).toContain('Status unavailable');
  expect(mount.querySelector('[data-ai-state="revoked"]')).toBeNull();
});
it('Settings → Node exposes AI-only revocation commands with working copy buttons', async () => {
  const { ControlCenter } = await import('../src/control/Shell');
  const { sampleSource, SAMPLE_OWN_ID } = await import('../src/control/sample');
  const source = sampleSource({ firstLiveMs: 1e9 });
  source.aiPairing = async () => view('paired');
  const writeText = vi.spyOn(navigator.clipboard, 'writeText').mockResolvedValue();
  dispose = render(() => <ControlCenter source={source} active ready error={null} ownId={SAMPLE_OWN_ID} firstRun={<span />} />, mount);
  await vi.waitFor(() => expect(mount.querySelector('[data-tab="node"]')).not.toBeNull());
  (mount.querySelector('[data-tab="node"]') as HTMLButtonElement).click();
  await vi.waitFor(() => expect(mount.querySelector('[data-panel="node"] [data-ai-state="paired"]')).not.toBeNull());
  const button = [...mount.querySelectorAll('button')].find(b => b.textContent === 'Copy revoke ai pairing command')!;
  button.click();
  await vi.waitFor(() => expect(writeText).toHaveBeenCalledWith('konsensus pair-revoke --client-id a1'));
  expect(button.textContent).toBe('Copied');
  writeText.mockRestore();
});
